/* ────── 软件I2C 写操作 ────── */
static bool oled_i2c_write(const uint8_t *data, uint16_t length)
{
    uint16_t queued = 0;
    uint32_t timeout = 0;
    uint32_t status;

    while (!(DL_I2C_getControllerStatus(OLED_I2C_INST)
        & DL_I2C_CONTROLLER_STATUS_IDLE)) {
        if (++timeout >= OLED_I2C_TIMEOUT) return false;
    }

    DL_I2C_flushControllerTXFIFO(OLED_I2C_INST);
    queued = DL_I2C_fillControllerTXFIFO(OLED_I2C_INST, data, length);
    DL_I2C_startControllerTransfer(OLED_I2C_INST, SSD1306_I2C_ADDR,
        DL_I2C_CONTROLLER_DIRECTION_TX, length);

    timeout = 0;
    while (timeout++ < OLED_I2C_TIMEOUT) {
        status = DL_I2C_getControllerStatus(OLED_I2C_INST);
        if (status & DL_I2C_CONTROLLER_STATUS_ERROR) {
            DL_I2C_flushControllerTXFIFO(OLED_I2C_INST);
            return false;
        }

        if (queued < length && !DL_I2C_isControllerTXFIFOFull(OLED_I2C_INST)) {
            queued += DL_I2C_fillControllerTXFIFO(
                OLED_I2C_INST, data + queued, length - queued);
        }

        if (queued >= length
            && (status & DL_I2C_CONTROLLER_STATUS_IDLE)) {
            return true;
        }
    }

    return false;
}

static void oled_write_cmd(uint8_t cmd)
{
    uint8_t data[2] = {0x00, cmd};
    (void)oled_i2c_write(data, sizeof(data));
}

void Drv_OLED_Init(void)
{
    delay_ms(10);  /* 上电等待 */

    /* SSD1306 初始化序列 */
    oled_write_cmd(SSD1306_DISPLAYOFF);
    oled_write_cmd(SSD1306_SETDISPLAYCLOCKDIV);
    oled_write_cmd(0x80);          /* 建议频率 */
    oled_write_cmd(SSD1306_SETMULTIPLEX);
    oled_write_cmd(0x3F);          /* 64 MUX */
    oled_write_cmd(SSD1306_SETDISPLAYOFFSET);
    oled_write_cmd(0x00);          /* no offset */
    oled_write_cmd(SSD1306_SETSTARTLINE | 0x00);
    oled_write_cmd(SSD1306_CHARGEPUMP);
    oled_write_cmd(0x14);          /* enable charge pump */
    oled_write_cmd(SSD1306_MEMORYMODE);
    oled_write_cmd(0x00);          /* horizontal addressing mode */
    oled_write_cmd(SSD1306_SEGREMAP | 0x01);
    oled_write_cmd(SSD1306_COMSCANDEC);
    oled_write_cmd(SSD1306_SETCOMPINS);
    oled_write_cmd(0x12);
    oled_write_cmd(SSD1306_SETCONTRAST);
    oled_write_cmd(0xCF);
    oled_write_cmd(SSD1306_SETPRECHARGE);
    oled_write_cmd(0xF1);
    oled_write_cmd(SSD1306_SETVCOMDETECT);
    oled_write_cmd(0x40);
    oled_write_cmd(SSD1306_DISPLAYALLON_RESUME);
    oled_write_cmd(SSD1306_NORMALDISPLAY);
    oled_write_cmd(SSD1306_DISPLAYON);

    /* 清屏 */
    Drv_OLED_Clear();
    Drv_OLED_Display();
}

void Drv_OLED_Clear(void)
{
    memset(g_framebuf, 0x00, sizeof(g_framebuf));
}

static void oled_display_page(uint8_t page)
{
    uint16_t offset;

    if (page >= OLED_PAGES) return;

    oled_write_cmd(SSD1306_COLUMNADDR);
    oled_write_cmd(0);
    oled_write_cmd(127);
    oled_write_cmd(SSD1306_PAGEADDR);
    oled_write_cmd(page);
    oled_write_cmd(page);

    offset = page * OLED_WIDTH;
    g_i2c_txbuf[0] = 0x40;
    memcpy(&g_i2c_txbuf[1], &g_framebuf[offset], OLED_WIDTH);
    (void)oled_i2c_write(g_i2c_txbuf, sizeof(g_i2c_txbuf));
}

void Drv_OLED_Display(void)
{
    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        oled_display_page(page);
    }
}

void Drv_OLED_SetCursor(uint8_t page, uint8_t col)
{
    if (page >= OLED_PAGES) page = OLED_PAGES - 1;
    if (col >= OLED_WIDTH) col = OLED_WIDTH - 1;
    g_cursor_page = page;
    g_cursor_col = col;
}

void Drv_OLED_ShowChar(char ch)
{
    uint8_t idx;

    if (ch < 0x20 || ch > 0x7E) ch = ' ';
    idx = (uint8_t)(ch - 0x20);

    if (g_cursor_page >= OLED_PAGES - 1 || g_cursor_col > OLED_WIDTH - 8) {
        return;
    }

    for (uint8_t i = 0; i < 8; i++) {
        g_framebuf[g_cursor_page * OLED_WIDTH + g_cursor_col + i] =
            g_font8x16[idx][i];
        g_framebuf[(g_cursor_page + 1) * OLED_WIDTH + g_cursor_col + i] =
            g_font8x16[idx][i + 8];
    }

    g_cursor_col += 8;
}

void Drv_OLED_ShowString(uint8_t page, uint8_t col, const char *str)
{
    Drv_OLED_SetCursor(page, col);
    while (*str) {
        Drv_OLED_ShowChar(*str);
        col += 8;
        if (col > 120) {
            col = 0;
            page++;
            if (page >= OLED_PAGES) break;
            Drv_OLED_SetCursor(page, col);
        }
        str++;
    }
}
